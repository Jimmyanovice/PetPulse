const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true,...(process.env.PLAYWRIGHT_CHANNEL?{channel:process.env.PLAYWRIGHT_CHANNEL}:{})});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const base='http://127.0.0.1:8001';
 const before=(await (await page.request.get(base+'/api/pets')).json()).map(p=>p.id).sort((a,b)=>a-b);
 const name='【删除功能测试】'+Date.now();
 const created=await page.request.post(base+'/api/pets',{data:{name,species:'cat'}});
 assert.equal(created.status(),201);const pet=await created.json();
 assert.equal((await page.request.post(base+'/api/pets/'+pet.id+'/logs',{data:{content:'仅用于验证删除级联的临时日志'}})).status(),201);
 assert.equal((await page.request.delete(base+'/api/pets/'+pet.id)).status(),422);
 assert.equal((await page.request.post(base+'/api/pets/'+pet.id+'/deletion-confirmation',{data:{first_confirmed:false}})).status(),422);
 const token=await (await page.request.post(base+'/api/pets/'+pet.id+'/deletion-confirmation',{data:{first_confirmed:true}})).json();
 assert.equal((await page.request.delete(base+'/api/pets/'+pet.id,{data:{confirmation_token:token.confirmation_token,confirm_name:'名字错误'}})).status(),400);
 assert.equal((await page.request.delete(base+'/api/pets/'+pet.id,{data:{confirmation_token:'tampered',confirm_name:name}})).status(),409);
 let deletes=0;page.on('request',r=>{if(r.method()==='DELETE')deletes++;});
 await page.goto(base+'/?pet_id='+pet.id);
 await page.waitForFunction(n=>document.querySelector('#pet-name').textContent===n,name);
 await page.locator('#delete-pet-button').click();
 await page.locator('#cancel-delete-pet').click();assert.equal(deletes,0);
 await page.locator('#delete-pet-button').click();
 await page.locator('#confirm-delete-pet').click();
 await page.waitForSelector('#delete-name-label:not([hidden])');
 await page.locator('#delete-name-input').fill('不匹配');
 assert.equal(await page.locator('#confirm-delete-pet').isDisabled(),true);assert.equal(deletes,0);
 await page.locator('#cancel-delete-pet').click();
 assert.equal((await page.request.get(base+'/api/pets/'+pet.id)).status(),200);
 await page.locator('#delete-pet-button').click();
 await page.locator('#confirm-delete-pet').click();
 await page.waitForSelector('#delete-name-label:not([hidden])');
 await page.locator('#delete-name-input').fill(name);
 await page.locator('#confirm-delete-pet').click();
 await page.waitForFunction(()=>!document.querySelector('#delete-pet-dialog').open);
 assert.equal(deletes,1);
 assert.equal((await page.request.get(base+'/api/pets/'+pet.id)).status(),404);
 const after=(await (await page.request.get(base+'/api/pets')).json()).map(p=>p.id).sort((a,b)=>a-b);
 assert.deepEqual(after,before);assert.deepEqual(errors,[]);
 console.log('PASS: both cancellations preserve pet; wrong name/no confirmation/tampered token rejected; exactly one deletion after two confirmations; existing pets preserved; deleted test pet id='+pet.id);
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
