const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const path=require('node:path');
require('node:fs').mkdirSync(path.resolve('artifacts/rag-validation'),{recursive:true});
(async()=>{
 const browser=await chromium.launch({headless:true,...(process.env.PLAYWRIGHT_CHANNEL?{channel:process.env.PLAYWRIGHT_CHANNEL}:{})});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8001/');
 await page.waitForSelector('.pet-item');
 await page.waitForSelector('#consult-ai-button[href*="pet_id="]');
 assert.equal(await page.locator('#chat-form').count(),0);
 assert.equal(await page.locator('.analysis-panel').count(),0);
 await page.screenshot({path:path.resolve('artifacts/rag-validation/journal-redesign.png'),fullPage:true});
 const target=await page.locator('#consult-ai-button').getAttribute('href');
 await page.locator('#consult-ai-button').click();
 await page.waitForFunction(()=>document.querySelector('#profile').value.length>0);
 await page.waitForSelector('.pet-context-panel');
 await page.waitForFunction(()=>!document.querySelector('#ask').disabled);
 assert.equal(new URL(page.url()).search,new URL(target,'http://localhost').search);
 assert.equal(await page.locator('#profile').getAttribute('readonly'),'');
 const left=await page.locator('.pet-context-panel').boundingBox(),right=await page.locator('.conversation-panel').boundingBox();
 assert.ok(left.x<right.x);
 await page.screenshot({path:path.resolve('artifacts/rag-validation/conversation-redesign.png'),fullPage:true});
 await page.locator('#sandbox').click();
 await page.locator('#species').selectOption('dog');
 await page.locator('#logs').fill('近三天喝水增多，排尿增多，精神尚可。');
 await page.locator('#question').fill('狗最近喝水增多，应该记录什么？');
 await page.locator('#ask').click();
 await page.waitForSelector('.message.assistant',{timeout:240000});
 await page.waitForFunction(()=>!document.querySelector('#ask').disabled);
 await page.locator('#question').fill('你刚才提到的记录，具体要包含什么？');
 await page.locator('#ask').click();
 await page.waitForFunction(()=>document.querySelectorAll('.message.assistant').length===2,{},{timeout:240000});
 await page.waitForFunction(()=>!document.querySelector('#ask').disabled);
 assert.equal(await page.locator('.message.user').count(),2);
 await page.screenshot({path:path.resolve('artifacts/rag-validation/conversation-live.png'),fullPage:true});
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await page.screenshot({path:path.resolve('artifacts/rag-validation/conversation-mobile.png'),fullPage:true});
 assert.deepEqual(errors,[]);
 console.log('PASS: journal simplification, pet handoff, side-by-side cards/chat, two live turns, mobile layout, no browser errors');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
