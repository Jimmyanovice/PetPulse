const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const path=require('node:path');
require('node:fs').mkdirSync(path.resolve('artifacts/rag-validation'),{recursive:true});
(async()=>{
 const browser=await chromium.launch({headless:true,...(process.env.PLAYWRIGHT_CHANNEL?{channel:process.env.PLAYWRIGHT_CHANNEL}:{})});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8001/');
 await page.waitForSelector('#consult-ai-button[href*="pet_id="]');
 await page.locator('#consult-ai-button').click();
 await page.waitForFunction(()=>document.querySelector('#profile').value.length>0&&!document.querySelector('#ask').disabled);
 const left=await page.locator('.pet-context-panel').boundingBox(),right=await page.locator('.conversation-panel').boundingBox();
 assert.ok(left.x<right.x);
 assert.equal(await page.locator('#knowledge-view').isVisible(),false);
 assert.equal(await page.locator('#profile').evaluate(n=>n.readOnly),true);
 assert.equal(await page.locator('#logs').evaluate(n=>n.readOnly),true);
 await page.locator('#question').fill('尚未发送的问题');
 await page.screenshot({path:path.resolve('artifacts/rag-validation/pet-context-layout.png'),fullPage:true});
 await page.locator('#knowledge-link').click();
 await page.waitForSelector('#knowledge-view .card');
 assert.equal(await page.locator('#conversation-view').isVisible(),false);
 await page.locator('#filter').fill('饮水');
 assert.ok(await page.locator('#cards .card').count()>0);
 await page.screenshot({path:path.resolve('artifacts/rag-validation/knowledge-entry.png'),fullPage:true});
 await page.locator('#back-to-chat').click();
 assert.equal(await page.locator('#question').inputValue(),'尚未发送的问题');
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await page.screenshot({path:path.resolve('artifacts/rag-validation/pet-context-mobile.png'),fullPage:true});
 await page.locator('#knowledge-link').click();
 const knowledgeUrl=page.url();
 await page.reload();
 await page.waitForSelector('#knowledge-view .card');
 assert.equal(page.url(),knowledgeUrl);
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 assert.deepEqual(errors,[]);
 console.log('PASS: pet context left/chat right, separate knowledge entry, search, return preserves input, direct URL/reload, mobile, no JS errors');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
